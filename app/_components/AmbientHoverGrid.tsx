const ACTIVE_COUNT = 2; // Shorter trail for thinking effect

export default function AmbientHoverGrid() {
    const [currentFrame, setCurrentFrame] = useState(0);

    useEffect(() => {
        const totalFrames = ANIMATION_FRAMES.length;

        const i = setInterval(() => {
            setCurrentFrame((prev) => (prev + 1) % totalFrames);
        }, 150); // Timing for thinking effect

        return () => clearInterval(i);
    }, []);

    // Get active cells with trail effect
    const getActiveSet = () => {
        const activeMap = new Map<number, number>(); // cellIndex -> position in trail

        for (let trailPos = 0; trailPos < ACTIVE_COUNT; trailPos++) {
            const frameIndex =
                (currentFrame - trailPos + ANIMATION_FRAMES.length) %
                ANIMATION_FRAMES.length;

            const frame = ANIMATION_FRAMES[frameIndex];

            frame.forEach((row, r) => {
                row.forEach((cell, c) => {
                    if (cell === 1) {
                        const cellIndex = r * COLS + c;
                        // Only set if not already set (prioritize newer frames)
                        if (!activeMap.has(cellIndex)) {
                            activeMap.set(cellIndex, trailPos);
                        }
                    }
                });
            });
        }

        return activeMap;
    };

    const activeSet = getActiveSet();

    return (
        <div className="shrink-0 grid grid-cols-11 gap-x-1.5 gap-y-1.5 w-fit">
            {Array.from({ length: TOTAL }).map((_, i) => {
                const trailPos = activeSet.get(i);
                const isActive = trailPos !== undefined;

                return (
                    <motion.div
                        key={i}
                        animate={{
                            backgroundColor: isActive
                                ? "var(--foreground)"
                                : "var(--secondary)",
                            opacity: isActive ? 1 - trailPos! * 0.3 : 0.6,
                            scale:
                                isActive && trailPos === 0
                                    ? 1.25
                                    : isActive
                                      ? 1.1
                                      : 1,
                        }}
                        transition={{
                            duration: 0.2,
                            ease: "easeOut",
                        }}
                        whileHover={{
                            backgroundColor: "var(--foreground)",
                            scale: 1.3,
                            opacity: 1,
                        }}
                        className="size-3 lg:size-4 rounded-[2px]"
                    />
                );
            })}
        </div>
    );
}
